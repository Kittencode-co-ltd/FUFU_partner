import test from 'node:test';
import assert from 'node:assert/strict';
import { thaiBahtText } from '../public/js/utils/thai-baht.js';

test('Thai baht text for receipts', () => {
  const cases = [
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [580, 'ห้าร้อยแปดสิบบาทถ้วน'],
    [1251.5, 'หนึ่งพันสองร้อยห้าสิบเอ็ดบาทห้าสิบสตางค์'],
    [0.25, 'ยี่สิบห้าสตางค์'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    [1000001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [21000000, 'ยี่สิบเอ็ดล้านบาทถ้วน'],
    [12345678.9, 'สิบสองล้านสามแสนสี่หมื่นห้าพันหกร้อยเจ็ดสิบแปดบาทเก้าสิบสตางค์'],
    [535, 'ห้าร้อยสามสิบห้าบาทถ้วน'],
    [10.01, 'สิบบาทหนึ่งสตางค์'],
  ];
  for (const [n, words] of cases) assert.equal(thaiBahtText(n), words, String(n));
});
