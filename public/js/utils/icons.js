/**
 * Returns an inline SVG string.
 * @param {string} name  - icon key from PATHS
 * @param {string} cls   - Tailwind size classes (default 'w-4 h-4')
 * @param {object} opts  - { fill: bool, color: string }
 */
export function icon(name, cls = 'w-4 h-4', { fill = false } = {}) {
  const d = PATHS[name];
  if (!d) {
    // Fallback: empty square so layout doesn't break
    return `<svg class="${cls} flex-shrink-0" viewBox="0 0 24 24" fill="none"></svg>`;
  }
  // Multi-path icons use space as separator
  const pathEls = d.split(' M ').map((seg, i) =>
    `<path stroke-linecap="round" stroke-linejoin="round" d="${i === 0 ? seg : 'M ' + seg}"/>`
  ).join('');
  return `<svg class="${cls} flex-shrink-0" fill="${fill ? 'currentColor' : 'none'}"
    stroke="${fill ? 'none' : 'currentColor'}" stroke-width="1.75"
    viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">${pathEls}</svg>`;
}

/** Shorthand for a small (w-4 h-4) icon */
export function icn(name) { return icon(name, 'w-4 h-4'); }

/** Icon with custom color via inline style */
export function iconColor(name, cls, color) {
  const svg = icon(name, cls);
  return svg.replace('<svg ', `<svg style="color:${color}" `);
}

/** Species avatar icon (dog / cat / bird, paw for anything else). */
export function speciesIcon(species, cls = 'w-5 h-5') {
  const name = { dog: 'dog', cat: 'cat', bird: 'dove' }[String(species || '').toLowerCase()] || 'paw';
  return icon(name, cls);
}
